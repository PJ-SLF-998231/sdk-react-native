// Exports the example and the SDK-free baseline for iOS and Android, measures them, checks that list/document/folder
// code is absent from the camera-only bundle, and writes ../docs/size-report.md.
//   cd example && npm install && (cd .. && npm ci && npm run build) && node scripts/size-report.mjs
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const example = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repo = resolve(example, '..');
const run = (cmd, args, cwd) => execFileSync(cmd, args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], env: { ...process.env, CI: '1' } });

const MARKERS_ABSENT = [
  'FolderList', 'FolderCard', 'FolderHeader', 'FolderBreadcrumb', 'DocumentList', 'DocumentRow', 'DocumentCard',
  'DocumentScreen', 'DocumentTextView', 'DocumentPreview', 'DocumentContentView', 'SiteRenderer',
  'useFolders', 'useFolder', 'useDocuments', 'useDocumentText', 'useDocumentSite', 'createFileThumbnailCache',
  'expo-document-picker', 'DocumentPickerButton', 'PhotoLibraryButton',
  '@shopify/flash-list', 'expo-file-system', 'react-native-gesture-handler', 'react-native-reanimated',
  'createAsyncStorageAdapter', 'createSqliteAdapter',
];
// react-native-document-scanner-plugin is the camera entry's own optional peer for mode="scan": its name is in the
// bundle (a guarded require), the package is not installed and no code from it is bundled.
const MARKERS_PRESENT = ['CameraButton', 'useCaptureUpload', 'expo-image-picker', 'react-native-document-scanner-plugin'];
// Package names are matched as quoted module ids, so prose in comments (Expo's docs mention expo-file-system) does not count.
const PACKAGES = new Set(['expo-document-picker', '@shopify/flash-list', 'expo-file-system', 'react-native-gesture-handler', 'react-native-reanimated', 'expo-image-picker', 'react-native-document-scanner-plugin']);
const has = (text, m) => (PACKAGES.has(m) ? text.includes(`"${m}"`) || text.includes(`'${m}'`) : text.includes(m));

function exportApp(dir, platform, mode) {
  // mode: 'hbc' (default release), 'js' (no bytecode, minified), 'raw' (no bytecode, not minified: readable names for the marker search)
  const out = join(dir, `dist-${platform}${mode === 'hbc' ? '' : '-' + mode}`);
  rmSync(out, { recursive: true, force: true });
  run('npx', ['expo', 'export', '--platform', platform, '--output-dir', out, ...(mode === 'hbc' ? [] : mode === 'js' ? ['--no-bytecode'] : ['--no-bytecode', '--no-minify'])], dir);
  const files = [];
  (function walk(d) { for (const n of readdirSync(d)) { const f = join(d, n); statSync(f).isDirectory() ? walk(f) : files.push(f); } })(join(out, '_expo', 'static', 'js'));
  const bundle = files.find((f) => /\.(hbc|js)$/.test(f));
  const buf = readFileSync(bundle);
  return { bundle, buf, bytes: buf.length, gzip: gzipSync(buf).length };
}

const kb = (n) => `${(n / 1024).toFixed(1)} KiB`;
const rows = [];
const proof = [];
for (const platform of ['ios', 'android']) {
  const app = exportApp(example, platform, 'hbc');
  const base = exportApp(join(example, 'baseline'), platform, 'hbc');
  rows.push({ platform, kind: 'Hermes bytecode (.hbc)', app, base });
  const appJs = exportApp(example, platform, 'js');
  const baseJs = exportApp(join(example, 'baseline'), platform, 'js');
  const raw = exportApp(example, platform, 'raw');
  rows.push({ platform, kind: 'JS, minified (--no-bytecode)', app: appJs, base: baseJs });
  const text = raw.buf.toString('utf8');
  const hbcText = app.buf.toString('latin1');
  proof.push({
    platform,
    absent: MARKERS_ABSENT.map((m) => ({ m, js: has(text, m), hbc: has(hbcText, m) })),
    present: MARKERS_PRESENT.map((m) => ({ m, js: has(text, m), hbc: has(hbcText, m) })),
  });
}
const check = run('npm', ['run', '--silent', 'check:size'], repo).trim();

const failures = proof.flatMap((p) => [...p.absent.filter((x) => x.js || x.hbc).map((x) => `${p.platform}: ${x.m} present`), ...p.present.filter((x) => !x.js).map((x) => `${p.platform}: ${x.m} missing from JS bundle`)]);

const md = [];
md.push('# Size report', '', 'Generated by `example/scripts/size-report.mjs`; do not edit by hand. Numbers are from one machine and one set of dependency versions (see `example/package.json`).', '');
md.push('## Example app vs. baseline', '', 'The example (`example/App.js`) imports only `@pj-slf-998231/sdk-react-native/camera` and renders one `CameraButton`. The baseline (`example/baseline/App.js`) is the same screen with a plain button and no SDK and no `expo-image-picker`. Both are exported with `expo export` (Metro, release mode).', '');
md.push('| Platform | Format | Example | Baseline (no SDK) | Delta | Delta gzip |', '|---|---|---|---|---|---|');
for (const r of rows) md.push(`| ${r.platform} | ${r.kind} | ${kb(r.app.bytes)} | ${kb(r.base.bytes)} | +${kb(r.app.bytes - r.base.bytes)} | +${kb(r.app.gzip - r.base.gzip)} |`);
md.push('', 'The delta is the SDK camera entry (client, outbox, cache, theme, capture button) plus `expo-image-picker`, since the baseline has neither. It is not the whole bundle and not an install size.', '');
md.push('## Camera-only claim: list, document and folder code is absent', '', 'Marker names searched for in the exported bundles (an unminified JS export so names are readable, and the release Hermes bytecode as raw bytes). "absent" must be true everywhere; "present" markers prove the search is not vacuous.', '');
for (const p of proof) {
  md.push(`### ${p.platform}`, '', '| Marker | Expected | In unminified JS | In bytecode |', '|---|---|---|---|');
  for (const x of p.present) md.push(`| \`${x.m}\` | present | ${x.js ? 'present' : 'ABSENT'} | ${x.hbc ? 'present' : 'absent'} |`);
  for (const x of p.absent) md.push(`| \`${x.m}\` | absent | ${x.js ? 'PRESENT' : 'absent'} | ${x.hbc ? 'PRESENT' : 'absent'} |`);
  md.push('');
}
md.push(`Result: ${failures.length ? 'FAILED (' + failures.join('; ') + ')' : 'every absent marker is absent and every present marker is present, on iOS and Android.'}`, '');
md.push('## Built size per entry', '', 'Output of `npm run check:size` (after `npm run build`): source graph and built bytes per entry, including the shared chunks it imports. Built bytes are unminified ESM from tsup, before Metro minifies; gzip is of the concatenated files.', '', '```', check, '```', '');
md.push('## Reproduce', '', '```sh', 'npm ci && npm run build            # repo root', 'cd example && npm install', 'node scripts/size-report.mjs        # exports ios + android, rewrites docs/size-report.md', '```', '');
writeFileSync(join(repo, 'docs', 'size-report.md'), md.join('\n'));
console.log(md.join('\n'));
if (failures.length) process.exit(1);
